// Helper to generate a custom exam from selected topics and count
export function generateCustomSimulado(
  disciplinas: string[],
  questionCount: number,
  segment: 'medio' | 'fundamental' = 'medio'
): Simulado {
  const allQuestions: Question[] = [];
  SIMULADOS_DATA.forEach(sim => {
    sim.questions.forEach(q => allQuestions.push(q));
  });

  // Pick questions matching disciplines or fallback
  const pool = allQuestions.length > 0 ? allQuestions : [];
  const selected: Question[] = [];
  
  for (let i = 0; i < questionCount; i++) {
    const baseQ = pool[i % pool.length];
    selected.push({
      ...baseQ,
      id: `custom-q-${i + 1}`,
      number: i + 1,
    });
  }

  return {
    id: `custom-${Date.now()}`,
    title: `Simulado Sob Medida — ${selected.length} Questões`,
    description: `Caderno personalizado com foco em ${disciplinas.join(', ')}. Cronometrado em condições reais de prova.`,
    badge: 'Caderno Personalizado',
    badgeType: 'tematico',
    segment,
    banca: 'enem',
    year: 2025,
    difficulty: 'medio',
    difficultyLabel: 'Personalizado',
    questionCount: selected.length,
    durationMinutes: Math.round(selected.length * 3),
    durationFormatted: `${Math.round(selected.length * 3)} min`,
    averageScorePercent: 65,
    studentsCountFormatted: 'Montado sob medida agora',
    benchmarkBadge: 'Treino Personalizado',
    curator: {
      name: 'Curadoria Inteligente',
      role: 'ESCSimulados Engine',
      avatar: 'https://lh3.googleusercontent.com/aida-public/AB6AXuD7Fcria8wrwxEs-Pps2YdhvPd_Q693d7kDY_ZzJvDvsjcvzlCEdVQNeld5W-o9wgfYq9EPEJWSkogp3QCMWqPZeNuLblhKsUA5W2c6xsXtD744TTBu3N4ZYORg3YuSBlu4kPsgAdYfGMsjKtOefOhVLCDV6EtKgf9o8DhqHMjzuwJ4mU9I2w6HrxupZFC6Ld2sHi7vZoPoQaFKx754mkEbP-ZSLfQyEo125wXAscs8-W8Tn_JNtkHetQ',
    },
    questions: selected,
  };
}
